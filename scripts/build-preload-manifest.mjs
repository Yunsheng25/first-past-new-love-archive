import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = path.join(ROOT, 'assets');
const OUTPUT = path.join(ROOT, 'preload-manifest.js');

async function walk(directory) {
  const items = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(items.map((item) => {
    const entry = path.join(directory, item.name);
    return item.isDirectory() ? walk(entry) : [entry];
  }));
  return files.flat();
}

const paths = (await walk(ASSETS))
  .map((entry) => path.relative(ROOT, entry).replaceAll('\\', '/'))
  .sort();
const entries = await Promise.all(paths.map(async (assetPath) => ({
  path: assetPath,
  bytes: (await stat(path.join(ROOT, assetPath))).size,
})));
const total = entries.reduce((sum, entry) => sum + entry.bytes, 0);
const source = [
  '// Generated by scripts/build-preload-manifest.mjs. Do not edit manually.',
  `export const PRELOAD_ASSETS = Object.freeze(${JSON.stringify(entries, null, 2)});`,
  `export const PRELOAD_TOTAL_BYTES = ${total};`,
  '',
].join('\n');

await writeFile(OUTPUT, source, 'utf8');
console.log(`Wrote ${entries.length} assets (${total} bytes) to preload-manifest.js`);
